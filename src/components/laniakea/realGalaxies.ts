// Module-level cache so we only fetch the dataset once per session
let cachedGalaxies: Galaxy[] | null = null;
let fetchPromise: Promise<Galaxy[]> | null = null;

/**
 * Fetch the full ~18,000 galaxy dataset from the API.
 * Returns a cached Promise on subsequent calls (deduplicates in-flight requests).
 */
export async function fetchGalaxiesFromAPI(): Promise<Galaxy[]> {
  if (cachedGalaxies) return cachedGalaxies;
  if (fetchPromise) return fetchPromise;

  fetchPromise = (async () => {
    try {
      const res = await fetch("/api/galaxies");
      if (!res.ok) {
        throw new Error(`Failed to fetch galaxies: ${res.status}`);
      }
      const data = (await res.json()) as CompactDataset;
      const galaxies = fromCompactDataset(data);
      cachedGalaxies = galaxies;
      return galaxies;
    } catch (err) {
      // Reset the promise so a retry can be attempted
      fetchPromise = null;
      throw err;
    }
  })();

  return fetchPromise;
}

